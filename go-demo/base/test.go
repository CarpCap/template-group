package main

import "fmt"

func main() {

	// -----------------------------------------
	// 1. 基础指针：& 取地址, * 解引用
	// -----------------------------------------
	fmt.Println("== 基础指针 ==")

	a := 10
	p := &a // p 是 *int，指向 a 的地址

	fmt.Println("a =", a)
	fmt.Println("p =", p)   // 地址
	fmt.Println("*p =", *p) // 解引用得到值

	*p = 20                      // 修改指针指向的数据
	fmt.Println("修改后 a =", a) // 输出 20

	// -----------------------------------------
	// 2. 指针作为函数参数（可修改外部变量）
	// -----------------------------------------
	fmt.Println("\n== 指针作为函数参数 ==")

	x := 5
	fmt.Println("修改前 x =", x)
	addOne(&x) // 传入 *int
	fmt.Println("修改后 x =", x)

	// -----------------------------------------
	// 3. 指向结构体的指针
	//    Go 自动解引用，不用写 (*u).Name
	// -----------------------------------------
	fmt.Println("\n== 结构体指针 ==")

	user := User{Name: "Tom", Age: 18}

	// 结构体取地址
	pu := &user

	fmt.Println("Name =", pu.Name) // 自动解引用
	fmt.Println("Age =", pu.Age)

	// 使用指针方法修改结构体内容
	pu.SetAge(20)
	fmt.Println("修改后 Age =", user.Age)

	// -----------------------------------------
	// 4. 切片本身就是一个“引用”，不需要指针也能修改
	// -----------------------------------------
	fmt.Println("\n== 切片本身引用语义 ==")

	nums := []int{1, 2, 3}
	fmt.Println("修改前 nums =", nums)

	modifySlice(nums)
	fmt.Println("修改后 nums =", nums)
}

// -----------------------------------------
// 函数：指针参数
// -----------------------------------------
func addOne(p *int) {
	*p = *p + 1
}

// -----------------------------------------
// 结构体
// -----------------------------------------
type User struct {
	Name string
	Age  int
}

// 指针 receiver：允许修改结构体内容
func (u *User) SetAge(newAge int) {
	u.Age = newAge
}
